CREATE TABLE USUARIOS (
	ID_USER SERIAL PRIMARY KEY,
	NOMBRE_USER VARCHAR(100) NOT NULL,
	EMAIL VARCHAR(150) UNIQUE NOT NULL,
	PASSWORD VARCHAR(200) NOT NULL,
	ROL VARCHAR(20) NOT NULL
);

CREATE TABLE CATEGORIA (
	ID_CATEGORIA SERIAL PRIMARY KEY,
	NOMBRE_CATEGORIA_en VARCHAR(100) NOT NULL,
	DESCRIPCION VARCHAR(100)
);

CREATE TABLE LIBROS (
	ID_BOOK SERIAL PRIMARY KEY,
	ID_CATEGORIA INT,
	TITULO VARCHAR(200) NOT NULL,
	AUTOR VARCHAR(100),
	SINOPSIS VARCHAR(1000),
	PORTADA_URL VARCHAR(500),
	FECHA_PUBLICACION DATE,
	STATUS VARCHAR(100),
	PRECIO NUMERIC(10, 2),
	STOCK INT,
	CONSTRAINT FK_LIBRO_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID_CATEGORIA)
);

CREATE TABLE ORDEN (
	ID_ORDEN SERIAL PRIMARY KEY,
	ID_USER INT NOT NULL,
	FECHA DATE NOT NULL,
	TOTAL NUMERIC(10, 2) NOT NULL,
	STATUS VARCHAR(100) NOT NULL,
	CONSTRAINT FK_ORDEN_USER FOREIGN KEY (ID_USER) REFERENCES USUARIOS (ID_USER)
);

CREATE TABLE DETALLEORDEN (
	ID_DETALLE SERIAL PRIMARY KEY,
	ID_ORDEN INT NOT NULL,
	ID_BOOK INT NOT NULL,
	CANTIDAD INT NOT NULL,
	PRECIO_LIBRO NUMERIC(10, 2) NOT NULL,
	SUBTOTAL NUMERIC(10, 2) NOT NULL,
	CONSTRAINT FK_DETALLE_ORDEN FOREIGN KEY (ID_ORDEN) REFERENCES ORDEN (ID_ORDEN),
	CONSTRAINT FK_DETALLE_LIBROS FOREIGN KEY (ID_BOOK) REFERENCES LIBROS (ID_BOOK)
);



